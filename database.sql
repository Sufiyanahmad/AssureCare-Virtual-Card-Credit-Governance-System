CREATE DATABASE IF NOT EXISTS nhas_assurecare_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE nhas_assurecare_db;

DROP TABLE IF EXISTS grievances_complaints;
DROP TABLE IF EXISTS deactivation_requests;
DROP TABLE IF EXISTS transactions_ledger;
DROP TABLE IF EXISTS appointments_prescriptions;
DROP TABLE IF EXISTS credit_wallets;
DROP TABLE IF EXISTS providers_registry;
DROP TABLE IF EXISTS users_beneficiaries;
DROP TABLE IF EXISTS mock_govt_kyc_registry;

-- 1. MOCK GOVT KYC REGISTRY (ONLY FOR AUTO-FETCH & MATCH DURING REGISTRATION)
CREATE TABLE mock_govt_kyc_registry (
    kyc_id INT AUTO_INCREMENT PRIMARY KEY,
    entity_type ENUM('CITIZEN','DOCTOR','BUSINESS_ORG') NOT NULL,
    id_number VARCHAR(20) UNIQUE NOT NULL,
    secondary_id VARCHAR(20) DEFAULT NULL,
    full_name VARCHAR(150) NOT NULL,
    dob_or_incorp DATE NOT NULL,
    gender_or_cat VARCHAR(40) NOT NULL,
    mobile_no VARCHAR(15) NOT NULL,
    district VARCHAR(80) NOT NULL,
    default_bank_acc VARCHAR(30) DEFAULT NULL,
    default_ifsc VARCHAR(15) DEFAULT NULL
) ENGINE=InnoDB;

-- 2. BENEFICIARIES / PATIENTS (EMPTY INITIALLY)
CREATE TABLE users_beneficiaries (
    beneficiary_id INT AUTO_INCREMENT PRIMARY KEY,
    aadhaar_no VARCHAR(12) UNIQUE NOT NULL,
    aadhaar_last4 VARCHAR(4) NOT NULL,
    assurecare_card_no VARCHAR(24) UNIQUE NOT NULL,
    card_last4 VARCHAR(4) NOT NULL,
    full_name VARCHAR(120) NOT NULL,
    dob DATE NOT NULL,
    gender ENUM('Male','Female','Other') NOT NULL,
    mobile_no VARCHAR(15) NOT NULL,
    district VARCHAR(80) NOT NULL,
    account_status ENUM('ACTIVE','FROZEN','DEACTIVATED') DEFAULT 'ACTIVE',
    freeze_reason VARCHAR(255) DEFAULT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- 3. PROVIDERS REGISTRY (INDEPENDENT & HOSPITAL-AFFILIATED UNITS)
CREATE TABLE providers_registry (
    provider_id INT AUTO_INCREMENT PRIMARY KEY,
    provider_card_no VARCHAR(24) UNIQUE NOT NULL,
    card_last4 VARCHAR(4) NOT NULL,
    role_type ENUM('HOSPITAL','DOCTOR','DIAGNOSTIC_LAB','PHARMACY') NOT NULL,
    org_or_doctor_name VARCHAR(150) NOT NULL,
    parent_hospital_card VARCHAR(24) DEFAULT NULL,
    hospital_share_pct DECIMAL(5,2) DEFAULT 0.00,
    doctor_degrees VARCHAR(120) DEFAULT NULL,
    doctor_aadhaar VARCHAR(12) DEFAULT NULL,
    doctor_aadhaar_last4 VARCHAR(4) DEFAULT NULL,
    business_pan VARCHAR(15) DEFAULT NULL,
    gst_number VARCHAR(20) DEFAULT NULL,
    bank_account_no VARCHAR(30) NOT NULL,
    bank_ifsc VARCHAR(15) NOT NULL,
    mobile_no VARCHAR(15) NOT NULL,
    district VARCHAR(80) NOT NULL,
    new_visit_fee DECIMAL(10,2) DEFAULT 500.00,
    revisit_validity_days INT DEFAULT 15,
    max_patients_per_day INT DEFAULT 30,
    is_verified TINYINT(1) DEFAULT 0,
    account_status ENUM('ACTIVE','FROZEN') DEFAULT 'ACTIVE',
    hold_reason VARCHAR(255) DEFAULT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- 4. ANNUAL CREDIT WALLETS
CREATE TABLE credit_wallets (
    wallet_id INT AUTO_INCREMENT PRIMARY KEY,
    assurecare_card_no VARCHAR(24) NOT NULL,
    calendar_year INT NOT NULL,
    base_5l_limit DECIMAL(12,2) DEFAULT 500000.00,
    base_5l_used DECIMAL(12,2) DEFAULT 0.00,
    extra_2_5l_approved TINYINT(1) DEFAULT 0,
    extra_2_5l_limit DECIMAL(12,2) DEFAULT 250000.00,
    extra_2_5l_used DECIMAL(12,2) DEFAULT 0.00,
    extra_repaid_principal DECIMAL(12,2) DEFAULT 0.00,
    interest_rate_pct DECIMAL(5,2) DEFAULT 5.00,
    UNIQUE KEY uk_card_year (assurecare_card_no, calendar_year),
    FOREIGN KEY (assurecare_card_no) REFERENCES users_beneficiaries(assurecare_card_no)
) ENGINE=InnoDB;

-- 5. APPOINTMENTS & PRESCRIPTIONS
CREATE TABLE appointments_prescriptions (
    rx_id INT AUTO_INCREMENT PRIMARY KEY,
    assurecare_card_no VARCHAR(24) NOT NULL,
    patient_name_locked VARCHAR(120) NOT NULL,
    provider_id INT NOT NULL,
    visit_type ENUM('NEW_VISIT','FREE_REVISIT') DEFAULT 'NEW_VISIT',
    fee_charged DECIMAL(10,2) DEFAULT 0.00,
    appointment_date DATE NOT NULL,
    revisit_valid_until DATE NOT NULL,
    next_followup_date DATE DEFAULT NULL,
    diagnosis_summary TEXT NOT NULL,
    prescribed_tests TEXT DEFAULT NULL,
    prescribed_medicines TEXT DEFAULT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (assurecare_card_no) REFERENCES users_beneficiaries(assurecare_card_no),
    FOREIGN KEY (provider_id) REFERENCES providers_registry(provider_id)
) ENGINE=InnoDB;

-- 6. IMMUTABLE LEDGER WITH PAYOUT SPLIT & SHA-256 HASH CHAINING
CREATE TABLE transactions_ledger (
    tx_id INT AUTO_INCREMENT PRIMARY KEY,
    assurecare_card_no VARCHAR(24) NOT NULL,
    provider_id INT DEFAULT NULL,
    parent_hospital_id INT DEFAULT NULL,
    rx_id INT DEFAULT NULL,
    section_type ENUM('DOCTOR_HOSPITAL','DIAGNOSTIC_LAB','PHARMACY','SYSTEM_CREDIT') NOT NULL,
    entry_direction ENUM('CREDIT','DEBIT') NOT NULL,
    credit_source ENUM('BASE_5L_ZERO_INT','EXTRA_2_5L_INTEREST','JAN1_AUTO_RECONCILE','DIRECT_REPAY') NOT NULL,
    amount DECIMAL(12,2) NOT NULL,
    hospital_share_amount DECIMAL(12,2) DEFAULT 0.00,
    provider_share_amount DECIMAL(12,2) DEFAULT 0.00,
    description VARCHAR(255) NOT NULL,
    prev_hash VARCHAR(64) NOT NULL,
    curr_hash VARCHAR(64) NOT NULL,
    tx_year INT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- 7. DEACTIVATION REQUESTS
CREATE TABLE deactivation_requests (
    req_id INT AUTO_INCREMENT PRIMARY KEY,
    assurecare_card_no VARCHAR(24) NOT NULL,
    request_year INT NOT NULL,
    attempt_no INT NOT NULL,
    death_cert_filename VARCHAR(255) NOT NULL,
    status ENUM('PENDING','APPROVED','REJECTED') DEFAULT 'PENDING',
    admin_reason VARCHAR(255) DEFAULT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- 8. GRIEVANCES & COMPLAINTS
CREATE TABLE grievances_complaints (
    complaint_id INT AUTO_INCREMENT PRIMARY KEY,
    tracking_no VARCHAR(24) UNIQUE NOT NULL,
    assurecare_card_no VARCHAR(24) NOT NULL,
    complainant_name_locked VARCHAR(120) NOT NULL,
    accused_provider_card VARCHAR(24) DEFAULT NULL,
    subject VARCHAR(180) NOT NULL,
    message TEXT NOT NULL,
    evidence_filename VARCHAR(255) DEFAULT NULL,
    stage ENUM('COMPLAINT_SUBMITTED','UNDER_SURVEILLANCE','TAKING_ACTION','FILE_CLOSED_SOLVED') DEFAULT 'COMPLAINT_SUBMITTED',
    admin_remark VARCHAR(255) DEFAULT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

DELIMITER //
CREATE TRIGGER trg_immutable_ledger_update BEFORE UPDATE ON transactions_ledger
FOR EACH ROW BEGIN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'IMMUTABLE LEDGER: Updates are strictly prohibited!';
END;//
CREATE TRIGGER trg_immutable_ledger_delete BEFORE DELETE ON transactions_ledger
FOR EACH ROW BEGIN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'IMMUTABLE LEDGER: Deletions are strictly prohibited!';
END;//
DELIMITER ;

